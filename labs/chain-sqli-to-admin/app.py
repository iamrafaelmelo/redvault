from __future__ import annotations

import secrets

from flask import redirect, request, session

from labkit import Lab

lab = Lab("ATLAS DIRECTORY", accent="#5c8df0")
app = lab.app

ADMIN_PASSWORD = secrets.token_urlsafe(24)
RECOVERY_CODE = str(secrets.randbelow(900000) + 100000)

schema = """
CREATE TABLE staff (id INTEGER PRIMARY KEY, name TEXT NOT NULL, role TEXT NOT NULL);
CREATE TABLE recovery_codes (username TEXT PRIMARY KEY, code TEXT NOT NULL);
"""
seed = [
    "INSERT INTO staff (name, role) VALUES ('Mara Chen', 'analyst');",
    "INSERT INTO staff (name, role) VALUES ('Ravi Singh', 'operator');",
    "INSERT INTO staff (name, role) VALUES ('Lena Ortiz', 'viewer');",
    f"INSERT INTO recovery_codes (username, code) VALUES ('admin', '{RECOVERY_CODE}');",
]
lab.init_db("atlas.db", schema, seed)

ACCOUNTS = {"admin": {"password": ADMIN_PASSWORD, "role": "admin"}}


def shell(title: str, body: str) -> object:
    nav = '<a href="/">Directory</a><a href="/recovery">Recovery</a><a href="/admin">Admin</a><a href="/login">Sign in</a>'
    return lab.page(title, f'<div class="hero"><div class="kicker">ATLAS // STAFF DIRECTORY</div><h1>{title}</h1></div>{body}', nav=nav)


@app.get("/")
@app.get("/directory")
def index():
    q = request.args.get("q", "")
    rows = []
    error = ""
    if q:
        conn = lab.db("atlas.db")
        try:
            # VULNERABLE: concatenated SQL over a database shared with recovery.
            rows = conn.execute(f"SELECT id, name, role FROM staff WHERE name LIKE '%{q}%'").fetchall()
        except Exception as exc:  # noqa: BLE001 - surfaced in the lab UI
            error = f'<div class="flash err">Query error: {exc}</div>'
        finally:
            conn.close()
    body = "".join(
        f'<div class="panel"><h3>{row["name"]}</h3><p>Role: {row["role"]}</p></div>' for row in rows
    )
    return shell(
        "Staff directory",
        f"""<div class="panel"><h2>Search the directory</h2>
        <form method="get" action="/"><label>Name contains</label><input name="q" value="{q}">
        <p><button type="submit">Search</button></p></form>{error}</div>
        <div class="grid">{body or '<p class="dim">Search for a colleague.</p>'}</div>""",
    )


@app.route("/login", methods=["GET", "POST"])
def login():
    message = ""
    if request.method == "POST":
        username = request.form.get("username", "")
        password = request.form.get("password", "")
        account = ACCOUNTS.get(username)
        if account and account["password"] == password:
            session.clear()
            session["user"] = username
            message = '<div class="flash ok">Signed in.</div>'
        else:
            message = '<div class="flash err">Invalid credentials.</div>'
    return shell(
        "Sign in",
        f"""<div class="panel"><h2>Atlas account</h2>
        <form method="post"><label>Username</label><input name="username">
        <label>Password</label><input name="password" type="password">
        <p><button type="submit">Sign in</button></p></form>{message}
        <p class="note">Forgot your password? Use the <a href="/recovery">recovery flow</a>.</p></div>""",
    )


@app.route("/recovery", methods=["GET", "POST"])
def recovery():
    message = ""
    if request.method == "POST":
        username = request.form.get("username", "")
        code = request.form.get("code", "")
        password = request.form.get("password", "")
        conn = lab.db("atlas.db")
        try:
            row = conn.execute("SELECT code FROM recovery_codes WHERE username = ?", (username,)).fetchone()
        finally:
            conn.close()
        # VULNERABLE: the code is not compared to an issued, bound, expiring secret
        # and there is no single-use invalidation.
        if row and row["code"] == code and len(password) >= 12:
            ACCOUNTS.setdefault(username, {"role": "user"})["password"] = password
            message = '<div class="flash ok">Password reset complete. <a href="/login">Sign in</a>.</div>'
        else:
            message = '<div class="flash err">Invalid recovery code.</div>'
    return shell(
        "Account recovery",
        f"""<div class="panel"><h2>Recover an account</h2>
        <form method="post"><label>Username</label><input name="username" value="admin">
        <label>Recovery code</label><input name="code">
        <label>New password (12+ characters)</label><input name="password" type="password">
        <p><button type="submit">Reset password</button></p></form>{message}
        <p class="note">Recovery codes are generated by the identity team and stored in the shared database.</p></div>""",
    )


@app.get("/admin")
def admin():
    if session.get("user") != "admin":
        return shell("Forbidden", '<div class="flash err">Administrator session required.</div>'), 403
    return shell(
        "Admin console",
        f'<div class="panel"><h2>Atlas administration</h2><pre>{lab.flag("flag")}</pre></div>',
    )


@app.get("/logout")
def logout():
    session.clear()
    return redirect("/")


if __name__ == "__main__":
    lab.run()